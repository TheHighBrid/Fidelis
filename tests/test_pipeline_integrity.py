ROOT = Path(__file__).resolve().parents[1]


class PipelineIntegrityTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(prefix='fidelis pipeline ')
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.source = np.random.default_rng(9).integers(30, 220, (13, 17, 3), dtype=np.uint8)
        self.input = self.root / 'source.png'
        self.output = self.root / 'output.png'
        Image.fromarray(self.source).save(self.input)
        runner = self.root / 'fixture runtime.py'
        runner.write_text('''import os,sys
from PIL import Image
mode=os.environ.get('FIDELIS_TEST_RUNTIME_MODE','good')
if mode=='error':raise SystemExit(7)
source,target=sys.argv[2:4]
with Image.open(source) as image:
 scale=3 if mode=='bad_dimensions' else 4
 image.resize((image.width*scale,image.height*scale),Image.Resampling.NEAREST).save(target)
''')
        self.cli = self.root / 'fidelis'
        self.cli.write_text('#!/usr/bin/env bash\nexec '+shlex.quote(sys.executable)+' '+shlex.quote(str(runner))+' "$@"\n')
        self.cli.chmod(0o755)
        self.pipeline = UpscalePipeline(cli_path=str(self.cli))
        self.pipeline.profiler.profile = lambda _: SimpleNamespace(noise_variance=0., has_faces=False, has_text=False)

    def run_pipeline(self, **overrides):
        return self.pipeline.run(self.input, self.output, tile_size=8, overlap=2,
                                 portrait=False, text_preserve=False, color_fix='none',
                                 post_telemetry=False, **overrides)

    def test_real_tiled_subprocess_and_unsigned_record(self):
        result = self.run_pipeline()
        with Image.open(self.output) as image:
            np.testing.assert_array_equal(np.array(image), self.source.repeat(4, 0).repeat(4, 1))
        self.assertEqual(result.output_dimensions, (68, 52))
        self.assertEqual(result.tile_execution['tile_strategy'], 'cosine_overlap')
        self.assertEqual(result.c2pa_status, 'unsigned')
        self.assertEqual(result.c2pa_manifest['signature_info']['status'], 'unsigned')
        self.assertFalse(result.c2pa_manifest['signature_info']['signed'])
        self.assertIsNone(result.c2pa_manifest['signature_info']['issuer'])
        sidecar = json.loads(self.output.with_suffix('.png.c2pa.json').read_text())
        self.assertEqual(sidecar['record_type'], 'unsigned_execution_record')
        self.assertEqual(sidecar['format'], 'application/json')
        self.assertEqual(sidecar['assertions'][1]['data']['output_sha256'], compute_sha256(self.output))
        self.assertEqual(result.spans[0]['attributes']['c2pa_status'], 'unsigned')
        self.assertIsNone(result.metrics['lpips'])
        self.assertIsNone(result.metrics['lpips_proxy'])
        self.assertIn('gradient_distance_proxy', result.metrics)
        self.assertEqual(result.metric_context['reference'], 'source_consistency')

    def test_runtime_error_and_malformed_tiles_do_not_publish_success(self):
        for mode in ('error', 'bad_dimensions'):
            with self.subTest(mode=mode), patch.dict(os.environ, {'FIDELIS_TEST_RUNTIME_MODE': mode}):
                with self.assertRaisesRegex(RuntimeError, 'Tiled upscale failed'):
                    self.run_pipeline()
                self.assertFalse(self.output.exists())
                self.assertFalse(self.output.with_suffix('.png.c2pa.json').exists())

    def test_unavailable_metrics_are_null_in_pipeline_record(self):
        with patch.object(pipeline_module.cv2, 'imread', return_value=None):
            result = self.run_pipeline()
        self.assertTrue(all(value is None for value in result.metrics.values()))
        self.assertEqual(result.metric_context['status'], 'unavailable')
        self.assertIn('null', json.dumps(result.to_dict(), allow_nan=False))

    def test_telemetry_reports_unsigned_and_reference_without_lpips_fabrication(self):
        # Avoid network I/O; capture the actual payload generated by run().
        with patch.object(self.pipeline, '_post_telemetry', return_value={'status':'unreachable'}) as post:
            result = self.pipeline.run(self.input,self.output,tiled=False,portrait=False,
                                       text_preserve=False,color_fix='none',post_telemetry=True)
        payload = post.call_args.args[1]
        self.assertEqual(payload['c2pa_status'],'unsigned')
        self.assertIsNone(payload['metrics']['lpips'])
        self.assertEqual(payload['metric_context']['reference'],'source_consistency')
        self.assertFalse(result.telemetry_posted)

    def test_optional_sidecar_failure_is_not_verified(self):
        Image.fromarray(self.source).save(self.output)
        with patch.object(pipeline_module.os, 'replace', side_effect=OSError('disk full')):
            record = generate_c2pa_provenance(self.input,self.output,'fixture',4,8,compute_sha256(self.output))
        self.assertFalse(record['sidecar_written'])
        self.assertEqual(record['signature_info']['status'],'unsigned')
        self.assertFalse(list(self.root.glob('.fidelis-provenance-*.tmp')))
        self.assertTrue(self.output.is_file())

    def test_telemetry_failure_has_bounded_timeout_and_does_not_raise(self):
        with patch.object(pipeline_module.urllib.request,'urlopen',side_effect=ConnectionRefusedError) as request:
            result = self.pipeline._post_telemetry('http://127.0.0.1:9/trace',{'metrics':{}})
        self.assertEqual(result['status'],'unreachable')
        self.assertLessEqual(request.call_args.kwargs['timeout'],2.)

    def test_cli_can_print_missing_metrics_without_invented_defaults(self):
        ground = self.root/'wrong reference.png'
        Image.new('RGB',(2,2)).save(ground)
        manifest = self.root/'manifest.json'
        env = {**os.environ,'PATH':str(self.root)+os.pathsep+os.environ['PATH']}
        command = [sys.executable,str(ROOT/'scripts/upscale.py'),str(self.input),str(self.output),
                   '--no-tiling','--no-text','--color-fix','none','--no-telemetry',
                   '--ground-truth',str(ground),'--json-manifest',str(manifest)]
        completed = subprocess.run(command,env=env,capture_output=True,text=True,check=True)
        self.assertIn('unavailable',completed.stdout)
        self.assertNotIn('LPIPS proxy:',completed.stdout)
        record = json.loads(manifest.read_text())
        self.assertIsNone(record['metrics']['psnr'])
        self.assertEqual(record['metric_context']['reason'],'ground_truth_dimensions_mismatch')


class MetricReferenceTests(unittest.TestCase):
    def setUp(self):
        self.source = np.zeros((12,14,3),np.uint8)
        self.source[:]=(0,0,255)  # BGR red
        self.output=np.zeros((48,56,3),np.uint8)
        self.output[:]=(0,255,0)  # BGR green

    def test_rgb_order_and_physical_cie76_units(self):
        metrics,context = measure_pipeline_metrics(self.source,self.output)
        self.assertGreater(metrics['cielab_delta_e'],169)
        self.assertLess(metrics['cielab_delta_e'],172)
        self.assertEqual(context['delta_e_method'],'CIE76_float_Lab')
        self.assertEqual(context['comparison_dimensions'],[14,12])

    def test_paired_ground_truth_uses_output_grid(self):
        metrics,context=measure_pipeline_metrics(self.source,self.output,
                              ground_truth_bgr=self.output.copy(),ground_truth_requested=True)
        self.assertEqual(metrics['ssim'],1.)
        self.assertEqual(metrics['cielab_delta_e'],0.)
        self.assertEqual(context['comparison_dimensions'],[56,48])
        self.assertEqual(context['reference'],'paired_ground_truth')

    def test_missing_reference_does_not_fall_back_to_source(self):
        for ground in (None,self.source):
            metrics,context=measure_pipeline_metrics(self.source,self.output,
                                   ground_truth_bgr=ground,ground_truth_requested=True)
            self.assertTrue(all(value is None for value in metrics.values()))
            self.assertEqual(context['status'],'unavailable')
            self.assertEqual(context['reference'],'paired_ground_truth')

    def test_decode_or_measurement_failure_does_not_emit_quality_constants(self):
        for source,output in ((None,self.output),(self.source,None)):
            metrics,context=measure_pipeline_metrics(source,output)
            self.assertTrue(all(value is None for value in metrics.values()))
        with patch.object(BenchmarkSuite,'compute_ssim',side_effect=ValueError('invalid measurement')):
            metrics,context=measure_pipeline_metrics(self.source,self.output)
        self.assertTrue(all(value is None for value in metrics.values()))
        self.assertEqual(context['reason'],'measurement_failed')


if __name__ == '__main__': unittest.main()
